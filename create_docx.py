from docx import Document
from docx.shared import Pt, Inches
from docx.enum.text import WD_ALIGN_PARAGRAPH
import sys

def main():
    doc = Document()
    
    # Title
    title = doc.add_heading('基于SDRE的航天器相对轨道估计与制导分析', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # 1. Background
    doc.add_heading('1. 项目背景', level=1)
    p = doc.add_paragraph(
        '随着航天技术的不断发展，航天器相对轨道协同、交会对接及抵近操作成为了空间领域的关键技术之一。'
        '在此背景下，针对椭圆轨道的非线性相对运动（NERM）模型进行高精度的相对状态估计与闭环制导（如SDRE控制）显得尤为重要。'
    )
    p.add_run(
        '本工作着眼于航天器在未知或干扰环境下的高精度自主接近与跟踪问题，考虑复杂的轨道动力学（包括线性与非线性椭圆相对运动模型及CW/LERM近似模型）。'
        '利用扩展卡尔曼滤波（EKF）融合相对量测（如测距、测角），并结合状态相关黎卡提方程（SDRE）实现大范围非线性系统下的最优反馈控制，'
        '从而确保追踪航天器对目标航天器的精准接近。在制导与接近过程中，本研究专注于自主制导与估计系统自身的协同性验证，而不涉及航天器间的对抗与博弈问题。'
    )
    
    # 2. Models
    doc.add_heading('2. 动力学、量测与制导模型', level=1)
    
    doc.add_heading('2.1 动力学模型', level=2)
    doc.add_paragraph(
        '考虑追踪航天器和目标航天器在局部垂线系（LVLH）下的相对运动。模型包含以下几种：'
    )
    doc.add_paragraph('（1）CW模型：用于近圆轨道的线性相对运动。')
    doc.add_paragraph('（2）LERM模型：参数随时间变化的椭圆轨道线性相对运动。')
    doc.add_paragraph('（3）NERM模型：全非线性椭圆相对运动模型（涵盖3D的13维和2D的9维闭环状态表示，包含真近点角演化）。')
    
    doc.add_paragraph(
        '系统本质可写为伪线性形式 x\u0307 = A(x)x + Bu，其中A(x)为状态相关系数（SDC）矩阵，以适配SDRE算法。LVLH坐标系约定x轴为径向，y轴为航向，z轴为轨道法向。'
    )
    
    doc.add_heading('2.2 量测模型', level=2)
    doc.add_paragraph(
        '系统的量测采用配置于追踪航天器上的相对传感器，输出目标的相对距离（ρ）、方位角（Azimuth）和俯仰角（Elevation）。\n'
        '其非线性量测方程为：\n'
        '  ρ = √(x\u00B2 + y\u00B2 + z\u00B2) + v_ρ\n'
        '  Az = arctan(y / x) + v_az\n'
        '  El = arcsin(z / ρ) + v_el \n'
        '其中 v 为传感器量测高斯白噪声。估计模块采用扩展卡尔曼滤波（EKF），通过模型一阶泰勒展开对测量更新进行非线性修正。'
    )
    
    doc.add_heading('2.3 制导与SDRE求解', level=2)
    doc.add_paragraph(
        '在实现对目标的接近制导中，由于相对运动学模型呈现出高度非线性特征，常规LQR在偏离平衡点较远时性能下降。'
        '故采用SDRE（状态相关黎卡提方程）方法。该方法在每个控制周期将非线性系统分解为伪线性反馈，'
        '实时求解代数黎卡提方程（ARE）：\n'
        '  A(x)ᵀ P(x) + P(x) A(x) - P(x) B R\u207B\u00B9 Bᵀ P(x) + Q = 0 '
    )
    doc.add_paragraph(
        '由上述解求得实时反馈控制律 u = -R\u207B\u00B9 Bᵀ P(x) x。计算过程中利用辛平衡（Symplectic Balancing）或稀疏更新策略保障实时性及数值稳定性。'
    )
    
    # 3. Scenarios
    doc.add_heading('3. 仿真情形', level=1)
    doc.add_paragraph(
        '为了全面验证该制导和估计框架的能力，仿真设计了多组涵盖不同初始条件的情形，主要考察相对面、相对轨道位置及机动的影响（有无机动、共面或异面、不同近点角初始条件等）：'
    )
    
    cases = [
        ("情形1：同平面同轨道不同位置", "追踪星和目标星在同一标称轨道平面、轨道高度相同，但存在一定的相位（初始沿轨距离、真近点角）差异，验证基础轨道追赶制导。"),
        ("情形2：不同平面同轨道", "两者轨道高度一致，但存在轨道倾角或升交点赤经偏差。考验立体空间上的跨平面交会与法向推力制导。"),
        ("情形3：同平面不同轨道（低轨到高轨）", "目标位于较高轨道，追踪星在低轨道且存在相位差，需同时执行轨道抬升与相位追赶制导。"),
        ("情形4：同平面不同轨道（高轨到低轨）", "目标位于较低轨道，追踪星在高轨道，验证降轨制导捕捉过程。"),
        ("情形5：不同平面且不同轨道", "综合异面、异高工况的三维大范围转移与合拢制导。"),
        ("情形6：目标不同初始相位角考察", "在同一条轨道上，改变目标星当前所在的真近点角位置（如近地点、远地点等），由于NERM和LERM是时变且依赖相位的，可观察推力最优解的受迫差异。"),
        ("情形7：有/无机动条件对比", "对比目标保持纯自然轨道运动（无机动）与目标执行不规则平动（如随机微推力调整等）情况，检验追踪器通过EKF跟踪与SDRE闭环修正的能力。")
    ]
    
    for title_text, desc in cases:
        p = doc.add_paragraph(style='List Bullet')
        p.add_run(f'{title_text}：').bold = True
        p.add_run(desc)
        
    # 4. Analysis
    doc.add_heading('4. 仿真分析', level=1)
    doc.add_paragraph(
        '根据仿真各情形的数据（如真值与EKF误差曲线、控制输入历史及三维相对轨迹等）可见：'
    )
    
    doc.add_paragraph(
        '1）估计性能分析：\n'
        '在无机动或低动态目标情形下，由于动力学方程能够紧密约束运动，EKF能够迅速收敛，距离和测角误差平滑降低至极小值。'
        '当初始轨道差异很大（如高低轨及不同面转移的场景下），虽然非线性模型会在初期导致较大的预测偏差，'
        '但依靠SDRE控制快速逼近目标后，截断误差与量测噪声对滤波的不利影响逐渐被抵消；在仅依赖不完整观测量（如距离测量不可信而退化为纯测角）的极限工况下，'
        'EKF能在运动过程中从角度序列中建立一定的三维距离关联，虽收敛变慢但位置精度仍保持在可控量级。'
    )
    doc.add_paragraph(
        '2）SDRE制导与轨迹表现：\n'
        '在同面与异面轨道转移制导中，SDRE均能平滑给出连续推力，不会因初始大偏差（如上千公里的距离与几十度的相位差）造成控制器的数值发散。'
        '同面不同轨道（情形3和情形4）下，最优推力表现出明显的变轨加速/减速阶段分布，一定程度上符合“霍曼转移”的最优能量消耗规律。'
        '在不同面且不同轨的情形（情形5）和受相位影响（情形6）中，SDRE不仅需要施加纵向与径向力，也在三维轨道机动中实时规划出法向推力分量修正轨道平面。'
    )
    doc.add_paragraph(
        '3）目标机动条件及未知因素影响：\n'
        '针对情形7（有/无机动条件对比），当目标不进行推力机动时，依靠精准建立的非线性椭圆相对运动模型（NERM），系统仅凭少量推力即可稳定贴合目标。\n'
        '若目标进行机动调整轨道，由于EKF实时更新残差并通过增益阵将目标的异常运动补偿至相对状态估计中，SDRE在每个控制步重新评估黎卡提方程与非线性状态矩阵，'
        '推力分配能迅速适应相对状态的跳变。相较于线性反馈（CW-LQR）可能产生的稳态误差，这种每步迭代的非线性反馈形式提供了更好的鲁棒性与制导精度。'
    )
    doc.add_paragraph(
        '结论：结合非线性相对量测建模、EKF滤波框架和SDRE连续制导策略的协同系统，在规避追逃对抗特征的同时，'
        '依然展现了在异面、异轨、大初始偏差及目标微机动工况下进行自主最优跟踪与交会捕获的卓越潜力。'
    )
    
    doc.save('项目说明文档.docx')
    print("Document successfully created: 项目说明文档.docx")

if __name__ == '__main__':
    main()
